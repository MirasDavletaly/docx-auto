/**
 * Перевод содержимого каталога: разделы, названия документов, поля формы.
 *
 * Строки интерфейса лежат в словарях `ru`/`en` по ключам. Содержимое
 * каталога устроено иначе: оно приходит данными (на сервере – из
 * `catalog/`), и ключом служит сама русская строка. Поэтому здесь не
 * словарь по ключам, а таблица «русский → английский».
 *
 * Переводится только то, что человек видит на экране. В сам документ перевод
 * не попадает: у бланка свои колонки на трёх языках, и значения полей
 * хранятся как ввели.
 */
import { lang } from './index';
import { contentEn } from './content-en';

/** Строка содержимого на текущем языке. Нет перевода – остаётся русская. */
export function tc(ru: string): string {
  if (lang === 'ru') return ru;
  return contentEn[ru] ?? ru;
}

/**
 * Название документа или шаблона на языке интерфейса. У шаблона из
 * конструктора английское название вписывает автор («Тест день 3»), у
 * документов каталога оно берётся из таблицы переводов.
 */
export function documentTitle(doc: { title: string; titleEn?: string }): string {
  if (lang === 'en' && doc.titleEn !== undefined && doc.titleEn.trim() !== '') return doc.titleEn;
  return tc(doc.title);
}
