/**
 * Деньги в тиынах (CLAUDE.md, п. 3.9): разбор ввода, сумма строки, НДС,
 * запись числом и прописью. Табличные тесты – здесь ошибка стоит денег.
 */
import { describe, expect, it } from 'vitest';

import {
  formatQuantity,
  formatTiyn,
  lineAmount,
  parseMoney,
  parseQuantity,
  quantityWords,
  tiynWords,
  vatIncluded,
} from './money';

describe('разбор суммы', () => {
  it.each([
    ['210', 21000n],
    ['210,5', 21050n],
    ['210.05', 21005n],
    ['1 234 567,89', 123456789n],
    ['1 234,5', 123450n],
    ['3.350,00', 335000n], // так записано в образце коммерческого предложения
    ['3,350.00', 335000n],
    ['1,234', 123400n], // три знака после запятой – это разряды, а не тиыны
    ['0', 0n],
    ['0,01', 1n],
  ])('«%s» → %s тиын', (text, tiyn) => {
    expect(parseMoney(text)).toBe(tiyn);
  });

  it.each(['', ' ', 'abc', '-5', '1,234,5', '1.2.3', '1,23,456', '12,3456'])('«%s» – не сумма', (text) => {
    expect(parseMoney(text)).toBeNull();
  });
});

describe('разбор количества', () => {
  it.each([
    ['4000', 4_000_000n],
    ['4 000', 4_000_000n],
    ['2,5', 2_500n],
    ['0.125', 125n],
    ['6,00', 6_000n],
  ])('«%s» → %s тысячных', (text, milli) => {
    expect(parseQuantity(text)).toBe(milli);
  });

  it.each(['', 'x', '-1', '1,2345'])('«%s» – не количество', (text) => {
    expect(parseQuantity(text)).toBeNull();
  });
});

describe('сумма строки: количество × цена, до тиына', () => {
  it.each([
    // образец накладной: 4 000 × 210 = 840 000
    [4_000_000n, 21000n, 84_000_000n],
    [6_000_000n, 21000n, 126_000_000n],
    // образец КП: 6 × 3 350 = 20 100
    [6_000n, 335000n, 2_010_000n],
    // 2,5 кг × 99,99 = 249,975 → 249,98 (половина тиына – вверх)
    [2_500n, 9999n, 24998n],
    // 0,333 × 1,00 = 0,333 → 0,33
    [333n, 100n, 33n],
    [0n, 21000n, 0n],
  ])('%s × %s = %s', (qty, price, amount) => {
    expect(lineAmount(qty, price)).toBe(amount);
  });
});

describe('НДС внутри суммы', () => {
  it.each([
    // 16 %: 1 160 → 160
    [116000n, 16, 16000n],
    // 840 000 с НДС 16 % → 115 862,07
    [84_000_000n, 16, 11_586_207n],
    // образец накладной считан по старой ставке 12 %: 840 000 → 90 000
    [84_000_000n, 12, 9_000_000n],
    [1n, 16, 0n],
    [0n, 16, 0n],
  ])('%s с НДС %s %% → НДС %s', (gross, rate, vat) => {
    expect(vatIncluded(gross, rate)).toBe(vat);
  });
});

describe('запись суммы', () => {
  it.each([
    [84_000_000n, 'kz', '840 000,00'],
    [210_000_000n, 'kz', '2 100 000,00'],
    [5n, 'kz', '0,05'],
    [2_010_000n, 'eu', '20.100,00'],
    [4_768_750n, 'eu', '47.687,50'],
    [335000n, 'eu', '3.350,00'],
  ] as const)('%s → «%s» (%s)', (tiyn, style, text) => {
    expect(formatTiyn(tiyn, style).replace(/ /gu, ' ')).toBe(text);
  });

  it.each([
    [4_000_000n, 'kz', '4 000'],
    [2_500n, 'kz', '2,5'],
    [125n, 'kz', '0,125'],
    [6_000n, 'eu', '6,00'],
    [2_500n, 'eu', '2,50'],
  ] as const)('количество %s → «%s» (%s)', (milli, style, text) => {
    expect(formatQuantity(milli, style).replace(/ /gu, ' ')).toBe(text);
  });
});

describe('сумма прописью с тиынами', () => {
  it.each([
    [0n, 'Ноль тенге 00 тиын'],
    [100n, 'Один тенге 00 тиын'],
    [200n, 'Два тенге 00 тиын'],
    [500n, 'Пять тенге 00 тиын'],
    [1100n, 'Одиннадцать тенге 00 тиын'],
    [2100n, 'Двадцать один тенге 00 тиын'],
    [100_000n, 'Одна тысяча тенге 00 тиын'],
    [100_000_000n, 'Один миллион тенге 00 тиын'],
    [210_000_000n, 'Два миллиона сто тысяч тенге 00 тиын'], // образец накладной
    [12_345n, 'Сто двадцать три тенге 45 тиын'],
    [7n, 'Ноль тенге 07 тиын'],
  ])('%s → «%s»', (tiyn, words) => {
    expect(tiynWords(tiyn)).toBe(words);
  });
});

describe('количество прописью', () => {
  it.each([
    [10_000_000n, 'Десять тысяч'], // образец накладной: 4 000 + 6 000
    [1_000n, 'Один'],
    [2_000n, 'Два'],
    [2_500n, '2,5'], // дробное – числом: слова для долей в форме не нужны
  ])('%s → «%s»', (milli, words) => {
    expect(quantityWords(milli)).toBe(words);
  });
});
