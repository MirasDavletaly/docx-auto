/**
 * Работник для выбора в формах: краткая карточка, без ИИН и оклада.
 *
 * С этапа 1б – карточка пользователя в персонале компании на сервере
 * (`GET /api/personnel`): `id` – идентификатор учётной записи, имя и его
 * формы – общие для всех компаний человека, должность и подразделение – в
 * этой компании.
 */
export interface EmployeeBrief {
  id: string;
  /**
   * Компания, в штате которой человек состоит. Работник одной компании не
   * должен появляться в списке выбора другой: это та же утечка между
   * компаниями, что и в документах (CLAUDE.md, п. 3.1).
   */
  companyId: string;
  fullName: string;
  /**
   * ФИО в той форме, в какой оно стоит после глагола приказа: «принять
   * Ахметова Асхата Каировича», «предоставить Ким Ирине Сергеевне».
   * Хранится, а не вычисляется: склонять фамилии программно нельзя.
   */
  fullNameGenitive: string;
  /**
   * ФИО на казахском в именительном падеже: «Сағын Дидар Есболұлы».
   * Пусто — в казахскую колонку идёт `fullName`, как записано в справочнике.
   */
  fullNameKk?: string;
  /**
   * ФИО на казахском в дательном падеже: «Нуржанов Диас Жанболатовичке».
   * В казахском приказе работник стоит именно так: «X-ке демалыс беру».
   * Падежное окончание зависит от последнего звука, программно его не берут.
   */
  fullNameKkDative?: string;
  /** ФИО латиницей: «Maksut Nauriyzgaliyev». В английской колонке приказа. */
  fullNameEn?: string;
  position: string;
  /** Должность на казахском и английском: они стоят в своих колонках приказа. */
  positionKk?: string;
  positionEn?: string;
  unit: string;
  /** Подразделение на казахском и английском: для колонок приказа и английского экрана. */
  unitKk?: string;
  unitEn?: string;
  /** Версия учётной записи человека на сервере (оптимистичная блокировка). */
  lockVersion?: number;
}

